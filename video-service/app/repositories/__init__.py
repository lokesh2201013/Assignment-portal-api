from typing import Protocol

from app.models import Video


class VideoRepository(Protocol):
    def get_by_id(self, video_id: int) -> Video | None: ...
    def update_status(self, video_id: int, status: str) -> None: ...
    def list_courses(self): ...
    def list_lessons(self, course_id: int): ...
    def get_lesson(self, video_id: int): ...
    def save_progress(self, video_id: int, learner_id: str, position: float, completed: bool): ...
    def get_progress(self, video_id: int, learner_id: str): ...
    def create_course(self, title: str, description: str, status: str): ...
    def update_course(self, course_id: int, title: str | None, description: str | None, status: str | None): ...
    def delete_course(self, course_id: int) -> None: ...
    def create_lesson(self, course_id: int, video_id: int, title: str, position: int, transcript: str): ...
    def update_lesson(self, lesson_id: int, title: str | None, position: int | None, transcript: str | None): ...
    def delete_lesson(self, lesson_id: int) -> None: ...
    def is_enrolled(self, course_id: int, learner_id: str) -> bool: ...
    def enroll(self, course_id: int, learner_id: str) -> None: ...
    def unenroll(self, course_id: int, learner_id: str) -> None: ...
    def list_enrollments(self, course_id: int): ...
    def create_incident(self, video_id: int, kind: str, detail: str): ...
    def list_incidents(self, status: str | None): ...
    def resolve_incident(self, incident_id: int) -> None: ...
